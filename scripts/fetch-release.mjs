// fetch-release.mjs — regenerate src/lib/release.ts from the live release
// metadata served publicly from the R2 bucket (the same data published to R2).
//
// Run in CI right before the site build so the download links always reflect
// the latest published release:
//
//   node scripts/fetch-release.mjs
//
// Env:
//   RELEASE_METADATA_URL  where to fetch latest.json (required in CI)
//   RELEASE_TS_PATH       where to write release.ts (default src/lib/release.ts)
//
// Offline / local dev: if the URL is unset or the fetch fails, this leaves the
// committed release.ts untouched (it doubles as an offline baseline) and exits
// successfully — the site still builds with no network.

const METADATA_URL = process.env.RELEASE_METADATA_URL;
const TS_PATH = process.env.RELEASE_TS_PATH ?? "src/lib/release.ts";

function esc(s) {
  return String(s ?? "")
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"');
}

function writeRelease(release) {
  const fp = release.signingKey.fingerprint ?? "";
  const lines = [];
  lines.push("/* eslint-disable */");
  lines.push("// AUTO-GENERATED by scripts/fetch-release.mjs from latest.json — do not edit by hand.");
  lines.push("// See docker/scripts/gen-release-metadata.sh for the source of this data.");
  lines.push('import type { ReleaseMetadata } from "./release-type";');
  lines.push("");
  lines.push("export const release: ReleaseMetadata = {");
  lines.push(`  tag: "${esc(release.tag)}",`);
  lines.push(`  version: "${esc(release.version)}",`);
  lines.push(`  arch: "${esc(release.arch)}",`);
  lines.push(`  filename: "${esc(release.filename)}",`);
  lines.push(`  publishedAt: "${esc(release.publishedAt)}",`);
  lines.push(`  sizeBytes: ${Number(release.sizeBytes) || 0},`);
  lines.push(`  sha256: "${esc(release.sha256)}",`);
  if (release.sha512) lines.push(`  sha512: "${esc(release.sha512)}",`);
  lines.push("  urls: {");
  lines.push(`    iso: "${esc(release.urls.iso)}",`);
  lines.push(`    sha256: "${esc(release.urls.sha256)}",`);
  if (release.urls.sha512) lines.push(`    sha512: "${esc(release.urls.sha512)}",`);
  lines.push(`    signature: "${esc(release.urls.signature)}"`);
  lines.push("  },");
  lines.push("  signingKey: {");
  lines.push(`    uid: "${esc(release.signingKey.uid)}",`);
  lines.push(`    fingerprint: "${esc(fp)}",`);
  lines.push(
    `    fingerprintTop: "${esc(
      release.signingKey.fingerprintTop ??
        fp
          .replace(/.{5}$/g, "")
          .replace(/(.{4})/g, "$1 ")
          .trim(),
    )}",`,
  );
  lines.push(
    `    fingerprintBot: "${esc(
      release.signingKey.fingerprintBot ??
        fp
          .replace(/^.{5}/g, "")
          .replace(/(.{4})/g, "$1 ")
          .trim(),
    )}",`,
  );
  lines.push(`    expires: "${esc(release.signingKey.expires)}"`);
  lines.push("  }");
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

if (!METADATA_URL) {
  console.log("[fetch-release] RELEASE_METADATA_URL not set — keeping committed release.ts (offline).");
  process.exit(0);
}

try {
  const res = await fetch(METADATA_URL);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const data = await res.json();
  if (!data.version || !data.urls?.iso) {
    throw new Error("metadata missing version/urls");
  }
  const fs = await import("node:fs");
  fs.writeFileSync(TS_PATH, writeRelease(data));
  console.log(`[fetch-release] wrote ${TS_PATH} -> ${data.tag} (${data.filename})`);
} catch (err) {
  console.warn(`[fetch-release] could not update release.ts (${err.message}) — keeping committed baseline.`);
  process.exit(0);
}
